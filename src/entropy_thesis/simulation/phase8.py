class Phase8DependencyError(RuntimeError):
    """Raised when optional AI dependencies are not installed."""


def _require_ai_dependencies():
    try:
        from sklearn.ensemble import RandomForestRegressor
        from sklearn.linear_model import LinearRegression
        from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score
        from xgboost import XGBRegressor
    except ImportError as exc:  # pragma: no cover - depends on local environment
        raise Phase8DependencyError(
            "Phase 8 AI 의존성이 없습니다. 프로젝트 루트에서 "
            "`python -m pip install -e .[ai]`를 먼저 실행하세요."
        ) from exc
    return {
        "LinearRegression": LinearRegression,
        "RandomForestRegressor": RandomForestRegressor,
        "XGBRegressor": XGBRegressor,
        "mean_absolute_error": mean_absolute_error,
        "mean_squared_error": mean_squared_error,
        "r2_score": r2_score,
    }


def _read_json(path: Path) -> dict[str, object]:
    if not path.exists():
        raise FileNotFoundError(path)
    with path.open("r", encoding="utf-8") as file:
        payload = json.load(file)
    if not isinstance(payload, dict):
        raise ValueError(f"JSON object가 필요합니다: {path}")
    return payload


def _required_columns(frame: pd.DataFrame, columns: Iterable[str], *, source: str) -> None:
    missing = [column for column in columns if column not in frame.columns]
    if missing:
        raise ValueError(f"{source}에 필요한 컬럼이 없습니다: {', '.join(missing)}")


def _zone_ids_from_allocations(allocations: pd.DataFrame) -> tuple[str, ...]:
    values = sorted(str(value) for value in allocations["zone_id"].dropna().unique())
    if not values:
        raise ValueError("allocation 데이터에 zone_id가 없습니다.")
    return tuple(values)


def build_phase8_feature_dataset(
    daily: pd.DataFrame,
    allocations: pd.DataFrame,
    *,
    include_targets: bool = True,
) -> tuple[pd.DataFrame, tuple[str, ...]]:
    """Build leakage-safe tabular features from pre-simulation operating conditions.

    `entropy_weight` is deliberately NOT used as an ML feature. Lambda only creates
    a candidate integer worker vector; once the vector is fixed, DES performance is
    determined by the operating condition and allocation itself. This also makes
    identical allocations generated by different lambda values receive identical
    predictions, preventing a spurious direct lambda effect.
    """

    _required_columns(
        daily,
        (*KEY_COLUMNS, *BASE_FEATURE_COLUMNS),
        source="daily candidate results",
    )
    _required_columns(
        allocations,
        (*KEY_COLUMNS, "zone_id", *ZONE_VALUE_COLUMNS),
        source="candidate allocations",
    )
    if include_targets:
        _required_columns(daily, (*TARGET_METRICS, "makespan_seconds"), source="daily candidate results")

    keys = list(KEY_COLUMNS)
    base_columns = list(BASE_FEATURE_COLUMNS)
    optional_daily = [
        column
        for column in ("observed_workers", "mean_release_delay_seconds")
        if column in daily.columns
    ]
    feature_frame = daily[keys + base_columns + optional_daily].copy()

    zone_ids = _zone_ids_from_allocations(allocations)
    for value_column in ZONE_VALUE_COLUMNS:
        pivot = allocations.pivot_table(
            index=keys,
            columns="zone_id",
            values=value_column,
            aggfunc="first",
        )
        pivot = pivot.reindex(columns=zone_ids)
        pivot.columns = [f"{value_column}_{zone_id}" for zone_id in zone_ids]
        feature_frame = feature_frame.merge(pivot.reset_index(), on=keys, how="left", validate="one_to_one")

    effective = feature_frame["effective_workers"].astype(float).replace(0.0, np.nan)
    feature_frame["tasks_per_worker"] = feature_frame["pick_tasks"].astype(float) / effective
    feature_frame["units_per_worker"] = feature_frame["picked_units"].astype(float) / effective

    workload_columns = [f"workload_share_{zone_id}" for zone_id in zone_ids]
    concentration_columns = [f"microzone_concentration_{zone_id}" for zone_id in zone_ids]
    worker_columns = [f"workers_{zone_id}" for zone_id in zone_ids]

    feature_frame["max_workload_share"] = feature_frame[workload_columns].max(axis=1)
    feature_frame["max_workers_zone"] = feature_frame[worker_columns].max(axis=1)
    feature_frame["weighted_microzone_concentration"] = 0.0
    feature_frame["worker_concentration_pair"] = 0.0
    for zone_id in zone_ids:
        share = feature_frame[f"workload_share_{zone_id}"].astype(float)
        concentration = feature_frame[f"microzone_concentration_{zone_id}"].astype(float)
        workers = feature_frame[f"workers_{zone_id}"].astype(float)
        feature_frame["weighted_microzone_concentration"] += share * concentration
        feature_frame["worker_concentration_pair"] += concentration * (workers * (workers - 1.0) / 2.0)

    # Macro-zone workload entropy is available before DES and complements the
    # within-zone micro-demand concentration used by the EWA objective.
    shares = feature_frame[workload_columns].to_numpy(dtype=float)
    positive = np.where(shares > 0.0, shares, 1.0)
    entropy_bits = -np.where(shares > 0.0, shares * np.log2(positive), 0.0).sum(axis=1)
    active_counts = (shares > 0.0).sum(axis=1)
    denom = np.where(active_counts > 1, np.log2(active_counts), 1.0)
    feature_frame["macro_workload_entropy_normalized"] = np.where(
        active_counts > 1, entropy_bits / denom, 0.0
    )

    feature_columns = tuple(
        column
        for column in feature_frame.columns
        if column not in KEY_COLUMNS and column != "mean_release_delay_seconds"
    )

    if include_targets:
        target_columns = [*TARGET_METRICS]
        for optional_target in ("makespan_seconds", "mean_release_delay_seconds"):
            if optional_target in daily.columns:
                target_columns.append(optional_target)
        feature_frame = feature_frame.merge(
            daily[keys + target_columns],
            on=keys,
            how="left",
            validate="one_to_one",
            suffixes=("", "_target"),
        )
        # If mean_release_delay_seconds was carried as an optional daily column,
        # keep only its target version and never expose it as a model feature.
        if "mean_release_delay_seconds_target" in feature_frame.columns:
            feature_frame["mean_release_delay_seconds"] = feature_frame.pop(
                "mean_release_delay_seconds_target"
            )

    if feature_frame[list(feature_columns)].isna().any().any():
        bad = feature_frame[list(feature_columns)].columns[
            feature_frame[list(feature_columns)].isna().any()
        ].tolist()
        raise ValueError("Phase 8 feature에 결측값이 있습니다: " + ", ".join(bad))

    return feature_frame.sort_values(list(KEY_COLUMNS)).reset_index(drop=True), feature_columns


def chronological_date_split(
    frame: pd.DataFrame,
    *,
    validation_ratio: float = DEFAULT_VALIDATION_RATIO,
) -> tuple[tuple[str, ...], tuple[str, ...]]:
    dates = tuple(sorted(str(value) for value in frame["selected_date"].unique()))
    if len(dates) < 5:
        raise ValueError("Phase 8 내부 날짜 검증을 위해 calibration 날짜가 최소 5개 필요합니다.")
    ratio = float(validation_ratio)
    if not math.isfinite(ratio) or not (0.05 <= ratio <= 0.5):
        raise ValueError("validation_ratio는 0.05~0.5 범위여야 합니다.")
    validation_count = max(1, int(math.ceil(len(dates) * ratio)))
    validation_count = min(validation_count, len(dates) - 1)
    return dates[:-validation_count], dates[-validation_count:]


def _xgb_model(*, seed: int = DEFAULT_SEED):
    deps = _require_ai_dependencies()
    XGBRegressor = deps["XGBRegressor"]
    return XGBRegressor(
        n_estimators=500,
        max_depth=3,
        learning_rate=0.03,
        subsample=0.85,
        colsample_bytree=0.85,
        reg_alpha=0.05,
        reg_lambda=1.0,
        objective="reg:squarederror",
        random_state=seed,
        n_jobs=4,
    )


def benchmark_models(
    frame: pd.DataFrame,
    feature_columns: tuple[str, ...],
    *,
    train_dates: Iterable[str],
    validation_dates: Iterable[str],
    seed: int = DEFAULT_SEED,
) -> pd.DataFrame:
    """Compare simple baselines with the designated XGBoost Phase-8 model."""

    deps = _require_ai_dependencies()
    LinearRegression = deps["LinearRegression"]
    RandomForestRegressor = deps["RandomForestRegressor"]
    mean_absolute_error = deps["mean_absolute_error"]
    mean_squared_error = deps["mean_squared_error"]
    r2_score = deps["r2_score"]

    train_set = set(str(value) for value in train_dates)
    validation_set = set(str(value) for value in validation_dates)
    train = frame[frame["selected_date"].astype(str).isin(train_set)]
    validation = frame[frame["selected_date"].astype(str).isin(validation_set)]
    if train.empty or validation.empty:
        raise ValueError("Phase 8 내부 학습/검증 데이터가 비어 있습니다.")

    records: list[dict[str, object]] = []
    for target in TARGET_METRICS:
        model_factories = {
            "linear_regression": lambda: LinearRegression(),
            "random_forest": lambda: RandomForestRegressor(
                n_estimators=400,
                min_samples_leaf=2,
                max_features=0.8,
                random_state=seed,
                n_jobs=-1,
            ),
            "xgboost": lambda: _xgb_model(seed=seed),
        }
        for model_name, factory in model_factories.items():
            model = factory()
            model.fit(train[list(feature_columns)], train[target])
            predicted = np.maximum(0.0, np.asarray(model.predict(validation[list(feature_columns)]), dtype=float))
            actual = validation[target].to_numpy(dtype=float)
            rmse = math.sqrt(float(mean_squared_error(actual, predicted)))
            records.append(
                {
                    "target": target,
                    "model": model_name,
                    "train_dates": len(train_set),
                    "validation_dates": len(validation_set),
                    "train_rows": len(train),
                    "validation_rows": len(validation),
                    "mae": float(mean_absolute_error(actual, predicted)),
                    "rmse": rmse,
                    "r2": float(r2_score(actual, predicted)),
                }
            )
    return pd.DataFrame(records)


def fit_xgboost_models(
    frame: pd.DataFrame,
    feature_columns: tuple[str, ...],
    *,
    dates: Iterable[str] | None = None,
    seed: int = DEFAULT_SEED,
) -> dict[str, object]:
    selected = frame
    if dates is not None:
        date_set = set(str(value) for value in dates)
        selected = frame[frame["selected_date"].astype(str).isin(date_set)]
    if selected.empty:
        raise ValueError("XGBoost 학습 데이터가 비어 있습니다.")
    models: dict[str, object] = {}
    for target in TARGET_METRICS:
        model = _xgb_model(seed=seed)
        model.fit(selected[list(feature_columns)], selected[target])
        models[target] = model
    return models


